"""Generate a static bash completion script for tether."""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

import click

APP_NAME = "tether"
MIN_BASH = (4, 4)


@dataclass
class _CommandSpec:
    """Completion metadata for one command in the Click tree."""

    id: int
    name: str
    options: list[str] = field(default_factory=list)
    children: list[tuple[str, int]] = field(default_factory=list)
    arguments: list[str] = field(default_factory=list)
    variadic: str | None = None


def completion_path(prog_name: str = APP_NAME) -> Path:
    """Return where the bash completion script should be written.

    ``BASH_COMPLETION_USER_DIR`` wins (first non-empty colon-separated entry),
    then ``XDG_DATA_HOME``, then ``~/.local/share``.
    """
    user_dir = os.environ.get("BASH_COMPLETION_USER_DIR", "")
    first = next((part for part in user_dir.split(":") if part), "")
    if first:
        base = Path(os.path.abspath(os.path.expanduser(first)))
    else:
        data_home = os.environ.get("XDG_DATA_HOME", "")
        base = (
            Path(os.path.abspath(os.path.expanduser(data_home)))
            if data_home
            else Path.home() / ".local" / "share"
        )
    return base / "bash-completion" / "completions" / f"{prog_name}.bash"


def install_bash_completion(
    group: click.Group, prog_name: str, version: str
) -> Path:
    """Write the completion script, print its path, and return the path."""
    path = completion_path(prog_name)
    _atomic_write(path, generate_bash(group, prog_name, version))
    click.echo(str(path))
    return path


def bash_version() -> tuple[int, int] | None:
    """Return the ``(major, minor)`` version of the bash on PATH, if any."""
    executable = shutil.which("bash")
    if executable is None:
        return None
    script = 'printf "%s.%s" "${BASH_VERSINFO[0]}" "${BASH_VERSINFO[1]}"'
    try:
        result = subprocess.run(
            [executable, "-c", script],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return None
    if result.returncode != 0:
        return None
    try:
        major, minor = result.stdout.strip().split(".", 1)
        return int(major), int(minor)
    except ValueError:
        return None


def completion_warning(version: tuple[int, int] | None) -> str | None:
    """Return a warning when bash cannot run the generated completion script."""
    if version is None:
        return (
            "bash was not found on PATH; completions require bash 4.4 or "
            "newer. zsh is not supported."
        )
    if version < MIN_BASH:
        major, minor = version
        return (
            f"bash {major}.{minor} is older than 4.4; the completion script "
            "requires bash 4.4 or newer. On macOS, /bin/bash is 3.2; install "
            "a newer bash (for example `brew install bash`). zsh is not "
            "supported."
        )
    return None


def generate_bash(group: click.Group, prog_name: str, version: str) -> str:
    """Return the complete static bash completion script."""
    specs = _collect(group, prog_name)
    lines = [
        "#!/usr/bin/env bash",
        f"# {prog_name} bash completion, version {version}",
        f"# Generated by `{prog_name} --completions`; do not edit, it is",
        "# overwritten the next time completions are generated.",
        "",
        "_tether_opts=(",
    ]
    lines.extend("  " + _bash_string("\n".join(spec.options)) for spec in specs)
    lines.append(")")
    lines.append("")
    lines.append("_tether_children=(")
    lines.extend(
        "  "
        + _bash_string(
            "\n".join(f"{name}:{cid}" for name, cid in spec.children)
        )
        for spec in specs
    )
    lines.append(")")
    lines.append("")
    lines.append("_tether_args=(")
    lines.extend(
        "  " + _bash_string(";".join(spec.arguments)) for spec in specs
    )
    lines.append(")")
    lines.append("")
    lines.append("_tether_variadic=(")
    lines.extend("  " + _bash_string(spec.variadic or "") for spec in specs)
    lines.append(")")
    lines.append("")
    lines.append(_RUNTIME)
    lines.append("")
    for spec in specs:
        lines.append(
            f"_tether_cmd_{spec.id}() {{ _tether_complete_cmd {spec.id}; }}"
        )
    lines.append("")
    lines.append("_tether_complete() { _tether_cmd_0; }")
    lines.append("")
    lines.append(
        "complete -o nosort -o bashdefault -o default "
        f"-F _tether_complete {_bash_string(prog_name)}"
    )
    return "\n".join(lines) + "\n"


def _collect(group: click.Group, prog_name: str) -> list[_CommandSpec]:
    specs: list[_CommandSpec] = []

    def walk(command: click.Command, name: str) -> int:
        spec = _CommandSpec(id=len(specs), name=name)
        specs.append(spec)
        spec.options = _option_specs(command)
        spec.arguments, spec.variadic = _argument_specs(command)
        if isinstance(command, click.Group):
            for child_name, child in command.commands.items():
                if getattr(child, "hidden", False):
                    continue
                child_id = walk(child, child_name)
                spec.children.append((child_name, child_id))
        return spec.id

    walk(group, prog_name)
    return specs


def _option_specs(command: click.Command) -> list[str]:
    specs: list[str] = []
    seen: set[str] = set()
    for param in command.params:
        if not isinstance(param, click.Option) or getattr(
            param, "hidden", False
        ):
            continue
        for name in [*param.opts, *param.secondary_opts]:
            if name in seen:
                continue
            seen.add(name)
            specs.append(_option_spec(param, name))
    # Click adds the help option separately from command.params.
    for name in ("-h", "--help"):
        if name not in seen:
            seen.add(name)
            specs.append(f"{name}|0")
    return specs


def _option_spec(param: click.Option, name: str) -> str:
    if param.is_flag or param.count:
        return f"{name}|0"
    nargs = (
        param.nargs if isinstance(param.nargs, int) and param.nargs > 0 else 1
    )
    types = _types_for(param.type, nargs)
    return "|".join([name, str(nargs), *types])


def _argument_specs(command: click.Command) -> tuple[list[str], str | None]:
    arguments: list[str] = []
    variadic: str | None = None
    for param in command.params:
        if not isinstance(param, click.Argument) or getattr(
            param, "hidden", False
        ):
            continue
        if param.nargs == -1:
            variadic = _type_spec(param.type)
            continue
        nargs = (
            param.nargs
            if isinstance(param.nargs, int) and param.nargs > 0
            else 1
        )
        arguments.extend(_types_for(param.type, nargs))
    return arguments, variadic


def _types_for(param_type: object, nargs: int) -> list[str]:
    if isinstance(param_type, click.Tuple):
        return [_type_spec(item) for item in param_type.types]
    return [_type_spec(param_type)] * max(nargs, 1)


def _type_spec(param_type: object) -> str:
    if isinstance(param_type, click.Choice):
        return "choice:" + ",".join(
            str(choice) for choice in param_type.choices
        )
    if isinstance(param_type, click.Path):
        if param_type.file_okay and param_type.dir_okay:
            return "path:any"
        if param_type.dir_okay:
            return "path:dir"
        return "path:file"
    if isinstance(param_type, click.File):
        return "path:file"
    return "none"


def _bash_string(value: str) -> str:
    return shlex.quote(value)


def _atomic_write(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        tmp.chmod(mode)
        tmp.replace(path)
    finally:
        if tmp.exists():
            tmp.unlink()


_RUNTIME = r"""
_tether_find_opt() {
    local cmd_id=$1
    local opt=$2
    local spec
    if [[ -z ${_tether_opts[cmd_id]} ]]; then
        return 1
    fi
    while IFS= read -r spec; do
        if [[ -n $spec && ${spec%%|*} == "$opt" ]]; then
            printf '%s' "$spec"
            return 0
        fi
    done <<< "${_tether_opts[cmd_id]}"
    return 1
}

_tether_find_child() {
    local cmd_id=$1
    local name=$2
    local entry
    if [[ -z ${_tether_children[cmd_id]} ]]; then
        return 1
    fi
    while IFS= read -r entry; do
        if [[ -n $entry && ${entry%%:*} == "$name" ]]; then
            printf '%s' "${entry#*:}"
            return 0
        fi
    done <<< "${_tether_children[cmd_id]}"
    return 1
}

_tether_files() {
    local cur=$1
    if declare -F _filedir >/dev/null 2>&1; then
        _filedir
    else
        mapfile -t COMPREPLY < <(compgen -f -- "$cur")
    fi
}

_tether_dirs() {
    local cur=$1
    if declare -F _filedir >/dev/null 2>&1; then
        _filedir -d
    else
        mapfile -t COMPREPLY < <(compgen -d -- "$cur")
    fi
}

_tether_any_path() {
    local cur=$1
    if declare -F _filedir >/dev/null 2>&1; then
        _filedir
    else
        mapfile -t COMPREPLY < <(compgen -f -- "$cur")
    fi
}

_tether_complete_kind() {
    local kind=$1
    local cur=$2
    local prefix=$3
    local value
    local index
    local -a values
    case $kind in
        choice:*)
            IFS=',' read -ra values <<< "${kind#choice:}"
            for value in "${values[@]}"; do
                if [[ $value == "$cur"* ]]; then
                    COMPREPLY+=("${prefix}${value}")
                fi
            done
            ;;
        path:file|file)
            _tether_files "$cur"
            for index in "${!COMPREPLY[@]}"; do
                COMPREPLY[index]="${prefix}${COMPREPLY[index]}"
            done
            ;;
        path:dir)
            _tether_dirs "$cur"
            for index in "${!COMPREPLY[@]}"; do
                COMPREPLY[index]="${prefix}${COMPREPLY[index]}"
            done
            ;;
        path:any)
            _tether_any_path "$cur"
            for index in "${!COMPREPLY[@]}"; do
                COMPREPLY[index]="${prefix}${COMPREPLY[index]}"
            done
            ;;
    esac
}

_tether_complete_spec() {
    local spec=$1
    local index=$2
    local cur=$3
    local prefix=$4
    local rest=${spec#*|}
    local types=${rest#*|}
    local kind=none
    local -a type_list
    if [[ -n $types ]]; then
        IFS='|' read -ra type_list <<< "$types"
        kind=${type_list[index]:-${type_list[${#type_list[@]}-1]}}
    fi
    _tether_complete_kind "$kind" "$cur" "$prefix"
}

_tether_complete_options() {
    local cmd_id=$1
    local cur=$2
    local spec
    local opt
    if [[ -z ${_tether_opts[cmd_id]} ]]; then
        return
    fi
    while IFS= read -r spec; do
        opt=${spec%%|*}
        if [[ -n $opt && $opt == "$cur"* ]]; then
            COMPREPLY+=("$opt")
        fi
    done <<< "${_tether_opts[cmd_id]}"
    if [[ "--" == "$cur"* ]]; then
        COMPREPLY+=("--")
    fi
}

_tether_complete_subcommands() {
    local cmd_id=$1
    local cur=$2
    local entry
    local name
    if [[ -z ${_tether_children[cmd_id]} ]]; then
        return
    fi
    while IFS= read -r entry; do
        name=${entry%%:*}
        if [[ -n $name && $name == "$cur"* ]]; then
            COMPREPLY+=("$name")
        fi
    done <<< "${_tether_children[cmd_id]}"
}

_tether_complete_positional() {
    local cmd_id=$1
    local pos=$2
    local cur=$3
    local args=${_tether_args[cmd_id]}
    local variadic=${_tether_variadic[cmd_id]}
    local -a specs
    if [[ -n $args ]]; then
        IFS=';' read -ra specs <<< "$args"
        if (( pos < ${#specs[@]} )); then
            _tether_complete_kind "${specs[pos]}" "$cur" ""
            return
        fi
    fi
    if [[ -n $variadic ]]; then
        _tether_complete_kind "$variadic" "$cur" ""
    fi
}

_tether_complete_cmd() {
    local cmd_id=$1
    local cur=${COMP_WORDS[COMP_CWORD]-}
    local i
    local w
    local spec
    local child
    local pos=0
    local ddash=0
    local expect=0
    local expect_spec=""
    local expect_index=0
    local nargs=0
    local -a parts
    COMPREPLY=()

    for ((i = 1; i < COMP_CWORD; i++)); do
        w=${COMP_WORDS[i]}
        if (( expect > 0 )); then
            expect=$((expect - 1))
            expect_index=$((expect_index + 1))
            if (( expect == 0 )); then
                expect_spec=""
            fi
            continue
        fi
        if (( !ddash )) && [[ $w == "--" ]]; then
            ddash=1
            continue
        fi
        if (( !ddash )) && [[ $w == -*=* ]]; then
            spec=$(_tether_find_opt "$cmd_id" "${w%%=*}") || spec=""
            if [[ -n $spec ]]; then
                IFS='|' read -ra parts <<< "$spec"
                nargs=${parts[1]}
                if (( nargs > 1 )); then
                    expect=$((nargs - 1))
                    expect_spec=$spec
                    expect_index=1
                fi
            fi
            continue
        fi
        if (( !ddash )) && [[ $w == -* ]]; then
            spec=$(_tether_find_opt "$cmd_id" "$w") || spec=""
            if [[ -n $spec ]]; then
                IFS='|' read -ra parts <<< "$spec"
                nargs=${parts[1]}
                if (( nargs > 0 )); then
                    expect=$nargs
                    expect_spec=$spec
                    expect_index=0
                fi
            fi
            continue
        fi
        child=$(_tether_find_child "$cmd_id" "$w") || child=""
        if [[ -n $child ]]; then
            cmd_id=$child
            pos=0
            continue
        fi
        pos=$((pos + 1))
    done

    if (( expect > 0 )) && [[ -n $expect_spec ]]; then
        _tether_complete_spec "$expect_spec" "$expect_index" "$cur" ""
        return
    fi

    if (( !ddash )) && [[ $cur == -*=* ]]; then
        spec=$(_tether_find_opt "$cmd_id" "${cur%%=*}") || spec=""
        if [[ -n $spec ]]; then
            _tether_complete_spec "$spec" 0 "${cur#*=}" "${cur%%=*}="
            compopt -o nospace 2>/dev/null || true
            return
        fi
    fi

    if (( !ddash )) && [[ $cur == -* ]]; then
        _tether_complete_options "$cmd_id" "$cur"
        return
    fi

    if (( pos == 0 && !ddash )) && [[ -n ${_tether_children[cmd_id]} ]]; then
        _tether_complete_subcommands "$cmd_id" "$cur"
        return
    fi

    _tether_complete_positional "$cmd_id" "$pos" "$cur"
}
"""
